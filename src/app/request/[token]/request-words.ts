/**
 * THE REQUEST WIZARD'S WORDS, IN ENGLISH AND IN NORWEGIAN (bokmål).
 *
 * The owner, 28 September 2026: a client who opens the wizard from a company
 * presentation we sent reads it in Norwegian. Everyone who comes from the site
 * keeps the English wizard, word for word as it was.
 *
 * Only what the client reads changes. The values the wizard stores and sends
 * (option keys, "Yes"/"No", "Immediate", the notes text, the role detail lines)
 * stay in English, because the ATS parses them: a Norwegian label here is a
 * display of an English value, never a replacement for it.
 *
 * No en or em dash anywhere in this file: the repository check rejects them.
 */
import { positionNb } from "@/lib/request-position-nb";

export type RequestLang = "en" | "no";

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Norwegian for a client who came from a presentation: a live presentation
 * ticket (the server's answer), or the presentation marks on the address (the
 * deck id, or source=presentation), which show the right language while the
 * ticket is still loading. The language never grants anything: access is the
 * token gate's alone.
 */
export function requestLangFrom(opts: { presentationTicket: boolean; source: string | null; deck: string | null }): RequestLang {
  if (opts.presentationTicket) return "no";
  if ((opts.source ?? "").trim() === "presentation") return "no";
  if (UUID.test((opts.deck ?? "").trim())) return "no";
  return "en";
}

/** "{name}" placeholders filled in. */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => (key in vars ? String(vars[key]) : whole));
}


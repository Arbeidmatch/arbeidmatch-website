/** One "Role details" row for the review, in the client's language. The stored line stays English. */
export function roleDetailRowLabel(lang: RequestLang, row: { label: string; value: string }): { label: string; value: string } {
  if (lang === "en") return row;
  const label = ROLE_DETAIL_LABEL_NB[row.label] ?? row.label;
  if (ROLE_DETAIL_AS_WRITTEN.has(row.label)) return { label, value: row.value };
  if (row.label === "Assignment period") {
    const w = REQUEST_WORDS.no;
    const both = /^(\d{4}-\d{2}-\d{2}) to (\d{4}-\d{2}-\d{2})$/.exec(row.value);
    if (both) return { label, value: fill(w.periodFromTo, { from: both[1], to: both[2] }) };
    const open = /^From (\d{4}-\d{2}-\d{2}), open-ended$/.exec(row.value);
    if (open) return { label, value: fill(w.periodFromOpen, { from: open[1] }) };
    const only = /^From (\d{4}-\d{2}-\d{2})$/.exec(row.value);
    if (only) return { label, value: fill(w.periodFromOnly, { from: only[1] }) };
    return { label, value: row.value };
  }
  return {
    label,
    value: row.value
      .split(", ")
      .map((part) => OPTION_NB[part] ?? part)
      .join(", "),
  };
}
